#!/usr/bin/env python3
"""Extract candidate CM11-era blobs from a locally unpacked system directory."""
import argparse
import hashlib
from pathlib import Path
import re
import shutil
import tempfile

PROJECT = Path(__file__).resolve().parents[1]
VARIANTS = ("kltetmo", "kltevzw")
PATH_PATTERN = re.compile(r"[A-Za-z0-9_./+-]+")


def blob_path(value):
    parts = value.split("/")
    if not PATH_PATTERN.fullmatch(value) or any(p in ("", ".", "..") for p in parts):
        raise ValueError(f"Invalid inventory path {value!r}")
    return Path(value)


def read_inventory(path):
    for line in path.read_text().splitlines():
        entry = line.split("#", 1)[0].strip()
        if not entry:
            continue
        source, _, destination = entry.removeprefix("-").partition(":")
        yield blob_path(source), blob_path(destination or source)


def extract(inventory, system, output, identity, profiles=None):
    entries = list(read_inventory(inventory / "proprietary-files.txt"))
    if profiles:
        selected = set()
        for profile in profiles:
            profile_file = inventory / f"{profile}-files.txt"
            if profile_file.is_file():
                selected.update(read_inventory(profile_file))
        unknown = selected.difference(entries)
        if unknown:
            raise ValueError(f"Profile contains unlisted files in {inventory.name}: {sorted(unknown)}")
        entries = [entry for entry in entries if entry in selected]
    files = {}
    missing = []
    for source, destination in entries:
        candidate = (system / source).resolve()
        if not candidate.is_relative_to(system) or not candidate.is_file():
            missing.append(str(source))
            continue
        if destination in files:
            raise ValueError(f"Duplicate destination: {destination}")
        files[destination] = candidate

    if missing:
        raise ValueError("Missing or out-of-tree firmware files: " + ", ".join(missing))

    copy_files = []
    modules = []
    android_mk = ["LOCAL_PATH := $(call my-dir)", ""]
    provenance = []
    for _, destination in entries:
        candidate = files[destination]
        blob = output / "proprietary" / destination
        blob.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(candidate, blob)
        if destination.parts[0] in ("bin", "xbin"):
            blob.chmod(0o755)
        with blob.open("rb") as stream:
            digest = hashlib.file_digest(stream, "sha256").hexdigest()
        provenance.append(f"{digest}  {destination}")
        if destination.suffix != ".apk":
            copy_files.append(f"    vendor/samsung/{inventory.name}/proprietary/{destination}:system/{destination}")
            continue

        module = f"crystal_{inventory.name}_{destination.stem}"
        modules.append(module)
        android_mk.extend([
            "include $(CLEAR_VARS)",
            f"LOCAL_MODULE := {module}",
            f"LOCAL_MODULE_STEM := {destination.stem}",
            "LOCAL_MODULE_CLASS := APPS",
            "LOCAL_MODULE_SUFFIX := .apk",
            "LOCAL_MODULE_TAGS := optional",
            "LOCAL_CERTIFICATE := PRESIGNED",
            f"LOCAL_SRC_FILES := proprietary/{destination}",
            "include $(BUILD_PREBUILT)",
            "",
        ])

    makefile = "# Generated by scripts/extract-blobs.py\n"
    if copy_files:
        makefile += "PRODUCT_COPY_FILES += \\\n" + " \\\n".join(copy_files) + "\n"
    if modules:
        makefile += "PRODUCT_PACKAGES += " + " ".join(modules) + "\n"
    (output / f"{inventory.name}-vendor.mk").write_text(makefile)
    if modules:
        (output / "Android.mk").write_text("\n".join(android_mk))
    (output / "firmware-source.txt").write_text(identity + "\n")
    (output / "SHA256SUMS").write_text("\n".join(provenance) + "\n")


def merge_vendor_profile(existing, profile):
    """Merge a freshly extracted profile into an existing vendor directory."""
    profile_files = {}
    for checksum in (profile / "SHA256SUMS").read_text().splitlines():
        digest, relative = checksum.split(None, 1)
        profile_files[relative] = digest

    sums_path = existing / "SHA256SUMS"
    sums = {}
    if sums_path.is_file():
        for checksum in sums_path.read_text().splitlines():
            digest, relative = checksum.split(None, 1)
            sums[relative] = digest

    for relative, digest in profile_files.items():
        source = profile / "proprietary" / relative
        target = existing / "proprietary" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        if source.stat().st_mode & 0o111:
            target.chmod(0o755)
        else:
            target.chmod(0o644)
        sums[relative] = digest

    sums_path.write_text("\n".join(
        f"{digest}  {relative}" for relative, digest in sorted(sums.items())
    ) + "\n")

    makefile = next(existing.glob("*-vendor.mk"), None)
    new_makefile = next(profile.glob("*-vendor.mk"), None)
    if new_makefile and new_makefile.is_file():
        destination = new_makefile.name
        current = makefile.read_text() if makefile and makefile.is_file() else "# Generated by scripts/extract-blobs.py\n"
        additions = new_makefile.read_text()
        copy_lines = [line.strip().rstrip("\\").strip()
                      for line in additions.splitlines()
                      if line.strip().startswith("vendor/samsung/")]
        existing_lines = [line.strip().rstrip("\\").strip()
                          for line in current.splitlines()
                          if line.strip().startswith("vendor/samsung/")]
        by_destination = {}
        order = []
        for line in existing_lines + copy_lines:
            if not line:
                continue
            _, sep, target_path = line.partition(":")
            if not sep:
                continue
            if target_path not in by_destination:
                order.append(target_path)
            by_destination[target_path] = line
        rendered = "# Generated by scripts/extract-blobs.py\n"
        if order:
            rendered += "PRODUCT_COPY_FILES += \\\n" + " \\\n".join(
                by_destination[target_path] for target_path in order
            ) + "\n"
        (existing / destination).write_text(rendered)

    identity = (profile / "firmware-source.txt").read_text().strip()
    source_path = existing / "firmware-source.txt"
    sources = source_path.read_text().splitlines() if source_path.is_file() else []
    if identity not in sources:
        sources.append(identity)
    source_path.write_text("\n".join(sources) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("variant", choices=VARIANTS)
    parser.add_argument("system", type=Path, help="Unpacked system directory")
    parser.add_argument("android_tree", type=Path)
    parser.add_argument("--firmware", required=True, help="Exact build identifier")
    parser.add_argument(
        "--common", action="store_true",
        help="Extract the shared inventory from this same firmware as well",
    )
    parser.add_argument(
        "--profile", choices=("graphics-thermal", "wifi", "bluetooth", "gsm-radio", "gps"),
        action="append",
        help="Extract a subsystem profile; may be repeated to combine profiles",
    )
    parser.add_argument(
        "--merge", action="store_true",
        help="Merge selected profile files into existing vendor directories",
    )
    args = parser.parse_args()
    system = args.system.resolve(strict=True)
    tree = args.android_tree.resolve(strict=True)
    if not (tree / "build" / "envsetup.sh").is_file():
        parser.error("android_tree must contain build/envsetup.sh")
    if system == tree or system.is_relative_to(tree / "vendor"):
        parser.error("Use an external, unpacked firmware directory")
    vendor = tree / "vendor" / "samsung"
    vendor.mkdir(parents=True, exist_ok=True)
    names = ["klte-common", args.variant] if args.common else [args.variant]
    for name in names:
        if not args.merge and ((vendor / name).exists() or (vendor / name).is_symlink()):
            parser.error(f"Existing vendor directory: {vendor / name}")
    with tempfile.TemporaryDirectory(prefix=".crystal-extract-", dir=vendor) as stage:
        for name in names:
            try:
                extract(PROJECT / "device" / "samsung" / name, system, Path(stage) / name,
                        args.firmware, args.profile)
            except ValueError as error:
                parser.error(str(error))
        for name in names:
            staged = Path(stage) / name
            if args.merge and (vendor / name).is_dir():
                merge_vendor_profile(vendor / name, staged)
            else:
                staged.rename(vendor / name)


if __name__ == "__main__":
    main()
